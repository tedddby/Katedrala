const BUILTIN_GLOBALS: ReadonlySet<string> = new Set([
  ...ECMASCRIPT,
  ...NODE,
  ...WEB,
  ...BROWSER,
  ...DOM_TYPES,
  ...TYPESCRIPT,
  ...AMBIENT,
]);

/** `HTMLDivElement`, `SVGPathElement`, ... and the constructor interfaces of built-ins (`ArrayConstructor`). */
const BUILTIN_PATTERNS: readonly RegExp[] = [
  /^(?:HTML|SVG|MathML)[A-Za-z]*Element$/,
  /^(?:HTML|SVG)[A-Za-z]*(?:Collection|List)$/,
  /^(?:Array|Boolean|Date|Error|Function|Map|Number|Object|Promise|RegExp|Set|String|Symbol|WeakMap|WeakSet)Constructor$/,
];

/** Whether an unbound identifier denotes a built-in global (see the module description). */
export function isBuiltinGlobal(name: string): boolean {
  return BUILTIN_GLOBALS.has(name) || BUILTIN_PATTERNS.some((pattern) => pattern.test(name));
}
